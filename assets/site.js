function bindLanguageSwitcher() {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      currentLang = button.dataset.lang;
      try { localStorage.setItem("properlyLang", currentLang); } catch (_) {}
      applyTranslations();
    });
  });
}

function bindFeaturedFilters() {
  document.querySelectorAll("[data-feature-filter]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.classList.contains("is-active")));
    button.addEventListener("click", () => {
      document.querySelectorAll("[data-feature-filter]").forEach((item) => {
        item.classList.toggle("is-active", item === button);
        item.setAttribute("aria-pressed", String(item === button));
      });
      renderFeatured();
    });
  });
}

function bindListingFilters() {
  const form = document.getElementById("listingFilters");
  if (!form) return;
  form.addEventListener("input", () => {
    form.dataset.edited = "true";
    renderListingsGrid();
  });
}

function bindHeroSearch() {
  const form = document.getElementById("homeSearch");
  if (!form) return;
  let mode = "buy";
  form.querySelectorAll("[data-search-mode]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.classList.contains("is-active")));
    button.addEventListener("click", () => {
      mode = button.dataset.searchMode;
      form.querySelectorAll("[data-search-mode]").forEach((item) => {
        item.classList.toggle("is-active", item === button);
        item.setAttribute("aria-pressed", String(item === button));
      });
    });
  });
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const params = new URLSearchParams(new FormData(form));
    params.set("mode", mode);
    window.location.href = `listings.html?${params.toString()}`;
  });
}

function hydrateListingFiltersFromUrl() {
  const form = document.getElementById("listingFilters");
  if (!form) return;
  const params = new URLSearchParams(window.location.search);
  params.forEach((value, key) => {
    if (form.elements[key]) form.elements[key].value = value;
  });
}

function bindForms() {
  document.querySelectorAll("[data-contact-form]").forEach((form) => {
    if (form.dataset.bound === "true") return;
    form.dataset.bound = "true";
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      const data = new FormData(form);
      const interest = form.querySelector('[name="interest"]');
      const lines = [
        "PROPERLY.SK",
        `${t("formName")}: ${String(data.get("name") || "").trim()}`,
        `Email: ${String(data.get("email") || "").trim()}`,
        `${t("formPhone")}: ${String(data.get("phone") || "").trim()}`,
        ...(interest?.value ? [`${t("formInterest")}: ${interest.selectedOptions[0].textContent}`] : []),
        "", `${t("formMessage")}:`, String(data.get("message") || "").trim()
      ];
      // Preserve the WhatsApp destination already configured in the GitHub repository.
      const phone = "421917962233";
      const text = encodeURIComponent(lines.join("\n"));
      const mobile = /Android|iPhone|iPad|iPod/i.test(navigator.userAgent);
      const url = mobile ? `https://wa.me/${phone}?text=${text}` : `https://api.whatsapp.com/send?phone=${phone}&text=${text}`;
      window.open(url, "_blank", "noopener,noreferrer");
      const status = form.querySelector(".form-status");
      if (status) status.textContent = t("formSent");
    });
  });
}

async function init() {
  bindLanguageSwitcher();
  bindFeaturedFilters();
  bindHeroSearch();
  bindListingFilters();
  bindForms();
  sourceLoading = Boolean(listingSourceUrl());
  applyTranslations();
  hydrateListingFiltersFromUrl();
  renderListingsGrid();
  try {
    await loadListingsFromBackend();
  } catch (_) {
    sourceUnavailable = true;
  }
  sourceLoading = false;
  applyTranslations();
  if (document.getElementById("listingFilters")?.dataset.edited !== "true") hydrateListingFiltersFromUrl();
  renderListingsGrid();
}

document.addEventListener("DOMContentLoaded", init);

function normalizeListingRecord(record) {
  const title = typeof record?.title === "string" ? record.title : record?.title?.sk;
  if (typeof record?.id !== "string" || !/^[\w-]+$/.test(record.id) || typeof record.location !== "string" || !record.location.trim() ||
      typeof title !== "string" || !title.trim() || !["buy", "rent"].includes(record.mode) ||
      !["apartment", "house", "commercial", "cottage", "land", "garage", "other"].includes(record.type)) {
    throw new Error("Listing requires an ID, location, title and transaction mode.");
  }
  const photos = (record.photos?.length ? record.photos : record.image ? [record.image] : []).map(safeUrl);
  if (record.isSample !== true && !record.sourceUrl) throw new Error("A real offer requires a source URL.");
  const optionalPositive = (value) => {
    if (value === null || value === undefined || value === "") return null;
    if (!Number.isFinite(Number(value)) || Number(value) <= 0) throw new Error("Invalid property measurement or price.");
    return Number(value);
  };
  const priceValue = optionalPositive(record.priceValue);
  const area = optionalPositive(record.area);
  const coverIndex = Math.min(Math.max(Math.trunc(Number(record.coverIndex)) || 0, 0), photos.length - 1);
  return {
    ...record, id: String(record.id), photos, coverIndex, image: photos[coverIndex],
    priceValue, area, rooms: record.rooms || "",
    priceText: priceValue === null ? "" : record.priceText || `${priceValue.toLocaleString("sk-SK").replace(/\u00a0/g, " ")} €`,
    description: record.description || {}, specs: record.specs || [],
    sourceUrl: record.sourceUrl ? safeUrl(record.sourceUrl) : "",
    isSample: record.isSample === true
  };
}


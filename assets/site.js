function bindGallery(root, listing, initial) {
  if (!listing.photos.length) return;
  let selected = initial;
  function selectPhoto(index) {
    selected = (index + listing.photos.length) % listing.photos.length;
    gallerySelections.set(listing.id, selected);
    const image = root.querySelector(".gallery-main");
    image.src = listing.photos[selected];
    image.alt = `${listingTitle(listing)} · ${t("photo")} ${selected + 1}`;
    root.querySelector(".gallery-main-link").href = listing.photos[selected];
    root.querySelector(".gallery-count").textContent = `${t("photo")} ${selected + 1} / ${listing.photos.length}`;
    root.querySelectorAll("[data-photo-index]").forEach((button) => {
      button.setAttribute("aria-pressed", String(Number(button.dataset.photoIndex) === selected));
    });
  }
  root.querySelectorAll("[data-photo-index]").forEach((button) => {
    button.addEventListener("click", () => selectPhoto(Number(button.dataset.photoIndex)));
  });
  root.querySelectorAll("[data-gallery-step]").forEach((button) => {
    button.addEventListener("click", () => selectPhoto(selected + Number(button.dataset.galleryStep)));
  });
}


async function loadListingsFromBackend() {
  const source = listingSourceUrl();
  if (!source) return;

  const response = await fetch(safeUrl(source), { signal: AbortSignal.timeout(15000) });
  if (!response.ok) throw new Error(`Unable to load listings from ${source}`);
  const payload = await response.json();
  const records = Array.isArray(payload) ? payload : payload.listings;
  if (!Array.isArray(records)) throw new Error("Listing source must be an array or { listings: [] }.");
  const normalized = records.map((record) => {
    const saved = embeddedListings.find((listing) => listing.id === record.id);
    // Reuse reviewed translations only while their original source version is unchanged.
    if (saved?.sourceUpdatedAt && saved.sourceUpdatedAt === record.sourceUpdatedAt) {
      record = { ...record, title: saved.title, description: saved.description };
    }
    return normalizeListingRecord(record);
  });
  if (new Set(normalized.map((listing) => listing.id)).size !== normalized.length) throw new Error("Duplicate listing IDs.");
  listings = normalized;
  sourceUnavailable = payload.stale === true;
  if (payload.refreshedAt && Number.isFinite(Date.parse(payload.refreshedAt))) {
    catalogueDate = new Date(payload.refreshedAt).toLocaleDateString("sk-SK", { timeZone: "UTC", day: "2-digit", month: "2-digit", year: "numeric" }).replace(/\s/g, "");
  }
}

function applyTranslations() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[currentLang][key]) {
      element.textContent = t(key);
    }
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === currentLang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  document.querySelectorAll("[data-source-status]").forEach((node) => {
    node.hidden = !sourceUnavailable && !sourceLoading;
    node.textContent = sourceLoading ? t("loadingOffers") : sourceUnavailable ? t("sourceUnavailable") : "";
  });
  refreshFilterOptions();
  renderDynamicAreas();
}

function refreshFilterOptions() {
  for (const formId of ["homeSearch", "listingFilters"]) {
    const form = document.getElementById(formId);
    if (!form) continue;
    for (const field of ["location", "type"]) {
      const select = form.elements[field];
      if (!select) continue;
      const selected = select.value;
      const values = [...new Set(listings.map((listing) => listing[field]))].sort((a, b) => a.localeCompare(b, "sk"));
      select.replaceChildren(new Option(t(field === "location" ? "filterAnyLocation" : "filterAnyType"), ""),
        ...values.map((value) => new Option(field === "type" ? typeLabel(value) : value, value)));
      if (values.includes(selected)) select.value = selected;
    }
  }
}

